import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({});
vm.runInContext(fs.readFileSync('src/airepredict/static/nearby.js','utf8'),context);
const {distance,nearest,locate}=context.AireNearby;
const position={latitude:-12.07,longitude:-77.04,accuracy:500};
assert.equal(distance(0,0,0,0),0);
assert(Math.abs(distance(0,0,0,1)-111.195)<.01);
assert.equal(distance(0,0,100,0),Infinity);
const sites=[{id:'far',latitude:-5,longitude:-80},{id:'close',latitude:-12.071,longitude:-77.041},{id:'invalid',latitude:null,longitude:null},{id:'near',latitude:-12.10,longitude:-77.01}];
assert.deepEqual(Array.from(nearest(sites,position),s=>s.id),['close','near']);
assert.equal(nearest(sites,{...position,accuracy:50000}).length,0);
assert.equal(nearest(sites,{latitude:40,longitude:0,accuracy:20}).length,0);
let requests=0;
const success=await locate({getCurrentPosition(ok,error,options){requests++;assert.equal(options.enableHighAccuracy,false);assert.equal(options.maximumAge,60000);ok({coords:position});}});
assert.equal(requests,1);assert.equal(success.latitude,position.latitude);
await assert.rejects(locate(undefined),/navegador no permite/);
await assert.rejects(locate({getCurrentPosition(ok,error){error({code:1});}}),/Permiso.*rechazado/);
await assert.rejects(locate({getCurrentPosition(ok,error){error({code:3});}}),/tardó demasiado/);
await assert.rejects(locate({getCurrentPosition(ok){ok({coords:{...position,latitude:200}});}}),/ubicación válida/);
console.log('Ubicación web: distancia, orden, cobertura, precisión, permiso y errores verificados.');
